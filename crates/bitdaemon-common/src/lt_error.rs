impl std::fmt::Display for LtError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.message())
    }
}

impl std::error::Error for LtError {}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn codes_and_messages() {
        assert_eq!(LtError::FailedHashCheck.code(), 2);
        assert_eq!(LtError::FailedHashCheck.message(), "hash check failed");
        assert_eq!(LtError::from_code(170), Some(LtError::ScrapeNotAvailable));
        assert_eq!(
            LtError::ScrapeNotAvailable.message(),
            "scrape not available on tracker"
        );
        assert_eq!(LtError::PartfileMissingPiece.code(), 220);
        assert_eq!(LtError::from_code(147), None);
        assert_eq!(LtError::message_of(147), "");
        assert_eq!(LtError::message_of(9999), "Unknown error");
        assert_eq!(MSGS.len(), ERROR_CODE_MAX as usize);
    }

    #[test]
    fn http_errors() {
        assert_eq!(
            HttpError::from_status(503),
            Some(HttpError::ServiceUnavailable)
        );
        assert_eq!(HttpError::NotFound.message(), "Not Found");
        assert_eq!(HttpError::from_status(418), None);
    }
}
